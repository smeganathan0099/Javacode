public class Array {
    public static void main(String[] args) {
        int[] marks = {350,450,498,415,445,491,379,479,389,371};
        String[] name = {"Sam", "Thivi", "Sanvi","Indhu","Raju",
            "Mega","Yogesh","Janaki","Prasath","Dharshana" };
        for (int i = 0; i < marks.length; i++) {
            System.out.println(name[i] + " = " + marks[i]);
        }
    }
}
